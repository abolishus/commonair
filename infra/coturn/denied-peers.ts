/**
 * The `denied-peer-ip` lines of infra/coturn/turnserver.conf, generated from the address ranges
 * the API never lets a user-supplied URL reach (`BLOCKED_V4`/`BLOCKED_V6` in
 * services/api/src/lib/netrange.ts), so the TURN relay can never reach them either: the host's
 * loopback services (coturn runs on the host network), private networks, metadata, multicast,
 * documentation, NAT64, Teredo and 6to4. coturn takes `start-end` ranges, not CIDR. Each IPv4
 * range is listed again in its IPv4-mapped IPv6 form (::ffff:a.b.c.d).
 *
 *   bun infra/coturn/denied-peers.ts           rewrite the block in turnserver.conf
 *   bun infra/coturn/denied-peers.ts --check   exit 1 when it is out of date
 *
 * infra/tests/coturn.test.ts runs the check, so the two lists cannot drift.
 */
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../../", import.meta.url).pathname;
export const NETRANGE = "services/api/src/lib/netrange.ts";
export const CONF = "infra/coturn/turnserver.conf";
export const BEGIN = "# BEGIN denied-peer-ip (generated by `bun infra/coturn/denied-peers.ts`; do not edit)";
export const END = "# END denied-peer-ip";

/** The CIDR strings of one `const NAME = [ ... ];` array in netrange.ts. */
export function blockedList(source: string, name: "BLOCKED_V4" | "BLOCKED_V6"): string[] {
  const m = new RegExp(`const ${name} = \\[([^\\]]*)\\];`).exec(source);
  if (!m?.[1]) throw new Error(`${NETRANGE} has no ${name}`);
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1] ?? "");
}

const v4ToInt = (ip: string) => ip.split(".").reduce((n, o) => n * 256n + BigInt(Number(o)), 0n);
const intToV4 = (n: bigint) => [24n, 16n, 8n, 0n].map((s) => String((n >> s) & 255n)).join(".");

function v6ToInt(ip: string): bigint {
  const [head = "", tail] = ip.split("::");
  const groups = (s: string) => (s ? s.split(":") : []);
  const h = groups(head);
  const t = tail === undefined ? [] : groups(tail);
  const zeros = tail === undefined ? 0 : 8 - h.length - t.length;
  const all = [...h, ...Array<string>(zeros).fill("0"), ...t];
  if (all.length !== 8) throw new Error(`not an IPv6 address: ${ip}`);
  return all.reduce((n, g) => (n << 16n) + BigInt(parseInt(g, 16)), 0n);
}

/** RFC 5952 text: lowercase, no leading zeros, the longest run (≥ 2) of zero groups as `::`. */
export function intToV6(n: bigint): string {
  const g = Array.from({ length: 8 }, (_, i) => Number((n >> BigInt((7 - i) * 16)) & 0xffffn));
  let best = -1;
  let bestLen = 1;
  for (let i = 0; i < 8;) {
    if (g[i] !== 0) {
      i++;
      continue;
    }
    let j = i;
    while (j < 8 && g[j] === 0) j++;
    if (j - i > bestLen) [best, bestLen] = [i, j - i];
    i = j;
  }
  const hex = g.map((x) => x.toString(16));
  if (best < 0) return hex.join(":");
  return `${hex.slice(0, best).join(":")}::${hex.slice(best + bestLen).join(":")}`;
}

/** [first, last] of a CIDR as integers. */
function bounds(cidr: string, bits: 32 | 128, parse: (ip: string) => bigint): [bigint, bigint] {
  const [base = "", len = ""] = cidr.split("/");
  const host = BigInt(bits - Number(len));
  const first = (parse(base) >> host) << host;
  return [first, first + (1n << host) - 1n];
}

/** The `denied-peer-ip=` lines, IPv4, then IPv6, then the IPv4-mapped forms. */
export function deniedPeerLines(source = readFileSync(`${ROOT}${NETRANGE}`, "utf8")): string[] {
  const v4 = blockedList(source, "BLOCKED_V4").map((c) => bounds(c, 32, v4ToInt));
  const v6 = blockedList(source, "BLOCKED_V6").map((c) => bounds(c, 128, v6ToInt));
  return [
    ...v4.map(([a, b]) => `denied-peer-ip=${intToV4(a)}-${intToV4(b)}`),
    ...v6.map(([a, b]) => `denied-peer-ip=${intToV6(a)}-${intToV6(b)}`),
    ...v4.map(([a, b]) => `denied-peer-ip=::ffff:${intToV4(a)}-::ffff:${intToV4(b)}`),
  ];
}

/** turnserver.conf with its generated block replaced. */
export function withDeniedBlock(conf: string, lines = deniedPeerLines()): string {
  const start = conf.indexOf(BEGIN);
  const end = conf.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${CONF} has no generated denied-peer-ip block`);
  return `${conf.slice(0, start)}${[BEGIN, ...lines].join("\n")}\n${conf.slice(end)}`;
}

if (import.meta.main) {
  const path = `${ROOT}${CONF}`;
  const current = readFileSync(path, "utf8");
  const next = withDeniedBlock(current);
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error(`${CONF} is out of date: run bun infra/coturn/denied-peers.ts`);
      process.exit(1);
    }
  } else if (next !== current) {
    writeFileSync(path, next);
    process.stdout.write(`wrote ${CONF}\n`);
  }
}
