/**
 * The ExecStopPost= order of the units Quadlet generates (scripts/selfhost/cgroup-reset.sh).
 *
 * quadlet.test.ts checks our .container files: each RestartMode=direct unit has the one
 * cgroup-reset.sh ExecStopPost=. What the fix relies on is the generated unit, where Quadlet
 * appends its own `podman rm` after ours. Observed with `quadlet -dryrun -user` on the source
 * units: Debian 13 (Podman 5.4.2), Fedora 42 (Podman 5.8.2) and Fedora CoreOS (Podman 6.1.4)
 * all generate [cgroup-reset.sh, podman rm]. The fixtures below are that output (the worker,
 * long lines shortened); the last test runs the generator itself when the machine has one.
 */
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, test } from "vite-plus/test";
import {
  CGROUP_RESET_STOP_POST,
  directUnits,
  execStopPosts,
  splitUnits,
  stopPostProblems,
} from "../../scripts/selfhost/e2e.ts";

const QUADLET_DIR = new URL("../quadlet/", import.meta.url).pathname;
const GENERATOR = "/usr/libexec/podman/quadlet";

/** `systemctl --user cat commonair-worker.service` on Debian 13 (Podman 5.4.2), abridged. */
const DEBIAN_WORKER = `# /run/user/1000/systemd/generator/commonair-worker.service
# Automatically generated by /usr/lib/systemd/user-generators/podman-user-generator
#
# SPDX-FileCopyrightText: 2026 CommonAir contributors
# SPDX-License-Identifier: CC0-1.0
#
# Background jobs (BullMQ).
[X-Container]
Notify=healthy

[Service]
# Leaves the cgroup as the next start needs it: RestartMode=direct skips systemd's own cleanup
# (scripts/selfhost/cgroup-reset.sh says why).
ExecStopPost=-/bin/sh %h/commonair/scripts/selfhost/cgroup-reset.sh
ExecStartPre=/bin/sh %h/commonair/scripts/selfhost/render-env.sh %h/commonair/infra/selfhost/env/commonair-worker.keys …
Restart=always
RestartMode=direct
RestartSec=5
RestartSteps=10
RestartMaxDelaySec=5min
TimeoutStartSec=300
Environment=PODMAN_SYSTEMD_UNIT=%n
KillMode=mixed
ExecStop=/usr/bin/podman rm -v -f -i --cidfile=%t/%N.cid
ExecStopPost=-/usr/bin/podman rm -v -f -i --cidfile=%t/%N.cid
Delegate=yes
Type=notify
NotifyAccess=all
SyslogIdentifier=%N
ExecStart=/usr/bin/podman run --name commonair-worker --cidfile=%t/%N.cid --replace --rm --cgroups=split … localhost/commonair/worker:latest

[Install]
WantedBy=default.target
`;

/** The same on Fedora 42 (Podman 5.8.2): Quadlet removes the container by name. */
const FEDORA_WORKER = DEBIAN_WORKER.replaceAll("--cidfile=%t/%N.cid --replace", "--replace").replaceAll(
  "-i --cidfile=%t/%N.cid",
  "-i commonair-worker",
);

const RESET = CGROUP_RESET_STOP_POST;
const RM_CID = "-/usr/bin/podman rm -v -f -i --cidfile=%t/%N.cid";
const RM_NAME = "-/usr/bin/podman rm -v -f -i commonair-worker";

describe("execStopPosts: the effective ExecStopPost= list of a unit", () => {
  test("Debian 13: the reset, then Quadlet's podman rm by cidfile", () => {
    expect(execStopPosts(DEBIAN_WORKER)).toEqual([RESET, RM_CID]);
    expect(stopPostProblems(execStopPosts(DEBIAN_WORKER))).toEqual([]);
  });

  test("Fedora 42: the reset, then Quadlet's podman rm by name", () => {
    expect(FEDORA_WORKER).toContain("ExecStop=/usr/bin/podman rm -v -f -i commonair-worker\n");
    expect(execStopPosts(FEDORA_WORKER)).toEqual([RESET, RM_NAME]);
    expect(stopPostProblems(execStopPosts(FEDORA_WORKER))).toEqual([]);
  });

  test("only [Service]: the same key in another section is not a command", () => {
    expect(execStopPosts("[Unit]\nExecStopPost=/bin/false\n[X-Container]\nExecStopPost=/bin/false\n")).toEqual([]);
    expect(execStopPosts("ExecStopPost=/bin/false\n")).toEqual([]);
  });

  test("comments, blank lines and spaces around = are handled as systemd does", () => {
    expect(
      execStopPosts("[Service]\n# ExecStopPost=/bin/a\n; ExecStopPost=/bin/b\n\nExecStopPost = /bin/c \n"),
    ).toEqual(["/bin/c"]);
  });

  test("an empty assignment clears the list; a drop-in after it appends", () => {
    const dropIn = `${DEBIAN_WORKER}\n# /home/commonair/.config/systemd/user/commonair-worker.service.d/10-op.conf\n[Service]\nExecStopPost=\nExecStopPost=/bin/true\n`;
    expect(execStopPosts(dropIn)).toEqual(["/bin/true"]);
    const appended = `${DEBIAN_WORKER}\n# drop-in\n[Service]\nExecStopPost=/bin/true\n`;
    expect(execStopPosts(appended)).toEqual([RESET, RM_CID, "/bin/true"]);
  });

  test("a continuation line is one command", () => {
    expect(execStopPosts("[Service]\nExecStopPost=/bin/sh -c \\\n  true\n")).toEqual(["/bin/sh -c    true"]);
  });

  test("an empty or missing unit has none", () => {
    expect(execStopPosts("")).toEqual([]);
  });
});

describe("stopPostProblems: the order cgroup-reset.sh relies on", () => {
  test.each([
    ["Quadlet's rm first (a reordering Podman)", [RM_CID, RESET], "[quadlet-rm, reset]"],
    ["no reset (dropped from the unit)", [RM_NAME], "[quadlet-rm]"],
    ["no Quadlet clean-up", [RESET], "[reset]"],
    ["nothing at all", [], "[none]"],
    ["the reset twice", [RESET, RESET, RM_CID], "[reset, reset, quadlet-rm]"],
    ["another command after Quadlet's", [RESET, RM_CID, "/bin/true"], "[reset, quadlet-rm, other(/bin/true)]"],
    ["the reset without its leading '-'", [RESET.slice(1), RM_CID], "other("],
    ["podman rm without -f", [RESET, "-/usr/bin/podman rm -v -i commonair-worker"], "other("],
  ])("%s fails", (_, entries, shown) => {
    const problems = stopPostProblems(entries);
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain(shown);
  });

  test("both Quadlet forms of its clean-up pass", () => {
    expect(stopPostProblems([RESET, RM_CID])).toEqual([]);
    expect(stopPostProblems([RESET, RM_NAME])).toEqual([]);
    expect(stopPostProblems([RESET, "-/usr/local/bin/podman rm -v -f -i commonair-api"])).toEqual([]);
  });
});

describe("splitUnits: the e2e's batched `systemctl cat`", () => {
  test("splits on the marker lines and keeps each unit's text", () => {
    const units = splitUnits(`@@unit commonair-api\n${DEBIAN_WORKER}@@unit commonair-web\nNo files found\n`);
    expect([...units.keys()]).toEqual(["commonair-api", "commonair-web"]);
    expect(execStopPosts(units.get("commonair-api")!)).toEqual([RESET, RM_CID]);
    expect(execStopPosts(units.get("commonair-web")!)).toEqual([]);
  });

  test("text before the first marker is dropped", () => {
    expect(splitUnits("noise\n@@unit a\nx")).toEqual(new Map([["a", "x\n"]]));
  });
});

describe("directUnits", () => {
  test("every long-running unit, and the one-shots that retry (migrate, storage-init)", () => {
    const units = directUnits();
    // 18 long-running (quadlet.test.ts) + migrate + storage-init; irc-cert is timer-driven.
    expect(units).toHaveLength(20);
    for (const u of ["commonair-worker", "commonair-postgres", "commonair-migrate", "commonair-storage-init"])
      expect(units).toContain(u);
    expect(units).not.toContain("commonair-irc-cert");
  });

  test("reads RestartMode=direct from the files", () => {
    const dir = mkdtempSync(join(tmpdir(), "quadlet-order-"));
    try {
      writeFileSync(join(dir, "a.container"), "[Service]\nRestartMode=direct\n");
      writeFileSync(join(dir, "b.container"), "[Service]\nRestartMode=normal\n");
      writeFileSync(join(dir, "c.volume"), "RestartMode=direct\n");
      expect(directUnits(dir)).toEqual(["a"]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

/** Podman's major version, or null without podman. */
function podmanMajor(): number | null {
  try {
    const r = Bun.spawnSync(["podman", "--version"], { stdout: "pipe", stderr: "pipe" });
    const m = /(\d+)\.\d+/.exec(r.stdout.toString());
    return m ? Number(m[1]) : null;
  } catch {
    return null;
  }
}

/** Generated units by name, from `quadlet -dryrun` output (`---name.service---` separators). */
function splitDryrun(output: string): Map<string, string> {
  const units = new Map<string, string>();
  let name = "";
  for (const line of output.split("\n")) {
    const m = /^---(.+)\.service---$/.exec(line);
    if (m) {
      name = m[1]!;
      units.set(name, "");
    } else if (name) units.set(name, `${units.get(name)}${line}\n`);
  }
  return units;
}

test("splitDryrun reads the generator's separators", () => {
  const units = splitDryrun(
    `---commonair-worker.service---\n${DEBIAN_WORKER}---commonair-network.service---\n[Unit]\n`,
  );
  expect([...units.keys()]).toEqual(["commonair-worker", "commonair-network"]);
  expect(execStopPosts(units.get("commonair-worker")!)).toEqual([RESET, RM_CID]);
});

// Podman 4.9 (CI's Ubuntu runners) cannot generate these units (Notify=healthy, HealthOnFailure
// and friends need Podman 5, which selfhost.sh requires), and macOS has no generator at all.
const major = existsSync(GENERATOR) ? podmanMajor() : null;
const skipReason =
  major === null
    ? `no Quadlet generator at ${GENERATOR} (not Linux, or no Podman): the e2e checks the generated units`
    : major < 5
      ? `Podman ${major} cannot generate the units (selfhost.sh requires Podman 5)`
      : "";

test.skipIf(skipReason !== "")(
  `the generator puts Quadlet's podman rm after our cgroup reset in every RestartMode=direct unit${skipReason ? ` (skipped: ${skipReason})` : ""}`,
  () => {
    const r = Bun.spawnSync([GENERATOR, "-dryrun", "-user"], {
      env: { ...process.env, QUADLET_UNIT_DIRS: QUADLET_DIR },
      stdout: "pipe",
      stderr: "pipe",
    });
    expect(r.exitCode, r.stderr.toString()).toBe(0);
    const generated = splitDryrun(r.stdout.toString());
    const expected = directUnits();
    expect(expected.filter((u) => !generated.has(u))).toEqual([]);
    const problems = expected.flatMap((u) =>
      stopPostProblems(execStopPosts(generated.get(u)!)).map((p) => `${u}: ${p}`),
    );
    expect(problems).toEqual([]);
  },
  30_000,
);
