/**
 * FNV-1a over UTF-16 code units: small, stable across runtimes (server and browser agree, so
 * generated art never changes on hydration), and good enough to spread slugs over a palette.
 */
export function artHash(text: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}
