/**
 * Builds the `captions` scenario's speech fixture (ADR 0011): `reference.txt` read by eSpeak NG's
 * formant synthesizer, then encoded to 16 kHz mono Opus as `speech.ogg`, with its REUSE sidecar.
 *
 *   bun harness/src/w2/captions/fixture.ts [--force]
 *
 * Uses a local `espeak-ng` when there is one, otherwise the pinned Debian image under Podman
 * (`apt-get install espeak-ng` inside it); ffmpeg encodes. eSpeak NG is GPL-3.0-or-later, but a
 * formant voice is generated from rules, with no recorded speech, so the audio holds nothing of
 * the tool's own and is dedicated CC0-1.0 like the transcript. Commit `speech.ogg` and its
 * `.license` once generated; the scenario regenerates it when it is missing.
 */
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const FIXTURE_DIR = fileURLToPath(new URL("../../../fixtures/captions/", import.meta.url));
export const REFERENCE_PATH = join(FIXTURE_DIR, "reference.txt");
export const SPEECH_PATH = join(FIXTURE_DIR, "speech.ogg");
/** eSpeak NG voice and rate: US English, a little slower than its default for the speech model. */
export const VOICE = { name: "en-us", wordsPerMinute: 150 } as const;
const DEBIAN_IMAGE =
  "docker.io/library/debian:trixie-20261005@sha256:913f6706df59a68922d1dd08f78c2476560a8d367897200a6005b00e5f67c2d5";

// REUSE-IgnoreStart
export const SPEECH_LICENSE = [
  "SPDX-FileCopyrightText: 2026 CommonAir contributors",
  "SPDX-License-Identifier: CC0-1.0",
  "",
  `Generated by harness/src/w2/captions/fixture.ts from reference.txt (CC0-1.0) with eSpeak NG`,
  `(GPL-3.0-or-later, https://github.com/espeak-ng/espeak-ng), formant voice ${VOICE.name} at`,
  `${VOICE.wordsPerMinute} words a minute: rule-based synthesis with no recorded voice data, so the`,
  "audio contains no part of the tool. Encoded with FFmpeg (libopus).",
  "",
].join("\n");
// REUSE-IgnoreEnd

function run(cmd: string[], what: string): void {
  const p = Bun.spawnSync(cmd, { stdout: "inherit", stderr: "inherit" });
  if (p.exitCode !== 0) throw new Error(`${what} failed (exit ${p.exitCode})`);
}

const has = (bin: string) => Bun.spawnSync(["sh", "-c", `command -v ${bin}`]).exitCode === 0;

/** Writes `speech.ogg` and its sidecar unless they exist (or `force`). Returns the audio path. */
export function generateSpeechFixture(force = false): string {
  if (existsSync(SPEECH_PATH) && !force) return SPEECH_PATH;
  const work = mkdtempSync(join(tmpdir(), "captions-fixture-"));
  try {
    const wav = join(work, "speech.wav");
    const espeak = ["-v", VOICE.name, "-s", String(VOICE.wordsPerMinute), "-f"];
    if (has("espeak-ng")) run(["espeak-ng", ...espeak, REFERENCE_PATH, "-w", wav], "espeak-ng");
    else if (has("podman"))
      run(
        [
          "podman",
          "run",
          "--rm",
          "-v",
          `${FIXTURE_DIR}:/fixture:ro,Z`,
          "-v",
          `${work}:/work:Z`,
          DEBIAN_IMAGE,
          "sh",
          "-c",
          `apt-get update -qq && apt-get install -y -qq --no-install-recommends espeak-ng >/dev/null && espeak-ng ${espeak.join(" ")} /fixture/reference.txt -w /work/speech.wav`,
        ],
        "espeak-ng in podman",
      );
    else throw new Error("neither espeak-ng nor podman is available to synthesize the captions fixture");
    run(
      [
        "ffmpeg",
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-i",
        wav,
        "-ac",
        "1",
        "-ar",
        "16000",
        "-c:a",
        "libopus",
        "-b:a",
        "32k",
        SPEECH_PATH,
      ],
      "ffmpeg",
    );
    writeFileSync(`${SPEECH_PATH}.license`, SPEECH_LICENSE);
    return SPEECH_PATH;
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

if (import.meta.main) console.log(`wrote ${generateSpeechFixture(process.argv.includes("--force"))}`);
