interface Takedown {
  requestId: string;
  deadlineAt: string;
  receiptAtMs: number;
}

async function submitTakedownApi(run: Run, urls: string[], fields: web.NciiFormInput): Promise<Takedown> {
  const api = run.ctx.platform.api();
  const res = await api.fetch(new Request(`${api.baseUrl}${AUTH_ROUTES.altchaChallenge}`));
  if (!res.ok) throw new Error(`ALTCHA challenge answered HTTP ${res.status}`);
  const altcha = await solveAltcha(await res.json());
  const r = await api.client.ncii.submit({
    requesterName: fields.name,
    requesterEmail: fields.email,
    relationship: "self",
    contentUrls: urls,
    description: fields.description,
    goodFaith: true,
    signature: fields.signature,
    altcha,
  });
  return { requestId: r.id, deadlineAt: r.deadlineAt, receiptAtMs: Date.now() };
}

