export default defineScenario({
  name: "trust-safety",
  description:
    "T0 live off air + legal-only evidence → evidence survives deletion → two-reviewer T0 dismissal → T2 label, 18+ gate, appeal → T1 restrict, mod queue, clear → upload rejected → NCII 48 h clock and block list; logs carry no frame data or emails",
  needs: ["api", "web", "media", "worker", "mail", "ffmpeg", "browser", "podman"],
  // Needs the compose override (fixture lists, scripted classifier, test hooks): not part of `full`.
  inFull: false,
  timeoutMs: 30 * 60_000,
  async run(ctx) {
    const sessions: WebSession[] = [];
    const state = { finished: false, softFailed: false };
    ctx.defer(async () => {
      if (!state.finished || state.softFailed) await screenshotSessions(ctx, sessions);
      await Promise.allSettled(sessions.map((s) => s.close()));
    });
    const check: ScenarioContext["check"] = (name, condition, details) => {
      if (!condition) state.softFailed = true;
      return ctx.check(name, condition, details);
    };
    await trustSafety(ctx, sessions, check);
    state.finished = true;
  },
});

async function screenshotSessions(ctx: ScenarioContext, sessions: readonly WebSession[]): Promise<void> {
  const dir = join(ctx.env.HARNESS_REPORT_DIR ?? DEFAULT_REPORT_DIR, `${ctx.runId}-${ctx.name}`);
  // Never screenshot the legal page: evidence must not leave the instance, even blurred.
  const files = (
    await Promise.all(sessions.filter((s) => !s.label.startsWith("legal")).map((s) => s.screenshotAll(dir)))
  ).flat();
  if (files.length > 0) ctx.data("screenshots", files);
}

async function trustSafety(
  ctx: ScenarioContext,
  sessions: WebSession[],
  check: ScenarioContext["check"],
): Promise<void> {
  const p = ctx.platform;
  const selected = parseSteps(ctx.param("steps", "all"));
  const { steps, added } = withPrerequisites(selected);
  const via = parseVia(ctx.param("via", "web"));
  const sampleSeconds = parseSampleSeconds(ctx.param("sampleSeconds", "2"));
  const deadlineMs = twoIntervalsDeadlineMs(sampleSeconds);
  ctx.data("steps", { selected, run: steps, addedPrerequisites: added });
  ctx.data("via", via);
  ctx.data("deadlines", { sampleSeconds, twoIntervalsMs: deadlineMs });

  const databaseUrl = ctx.env.DATABASE_URL;
  ctx.assert(
    "DATABASE_URL is set (role CLI and read-only checks; run from the repo root so Bun loads .env)",
    databaseUrl !== undefined,
  );
  const secret = internalSecret(ctx.env);
  ctx.assert(
    "INTERNAL_API_SECRET is set (test-hook routes; HARNESS_INTERNAL_API_SECRET or the repo .env)",
    secret !== undefined,
  );
  if (databaseUrl === undefined || secret === undefined) return;
  const hooks = new ModerationHooks(ctx.env.HARNESS_API_URL, secret, ctx.signal);

  const needles: LogNeedle[] = [...GENERIC_NEEDLES];
  for (const name of [FIXTURES.t0Csam, FIXTURES.t0Ncii])
    needles.push(...fixtureNeedles(name, readFixture(fixturePath(name))));

  const [l1, l2, mod, admin] = await ctx.step("sign up staff: legal ×2, moderator, admin (API)", () =>
    Promise.all([
      p.signUp({ prefix: "ts_legal1" }),
      p.signUp({ prefix: "ts_legal2" }),
      p.signUp({ prefix: "ts_mod" }),
      p.signUp({ prefix: "ts_admin" }),
    ]),
  );
  const roles: [SignedInUser, string][] = [
    [l1, "legal"],
    [l2, "legal"],
    [mod, "moderator"],
    [admin, "admin"],
  ];
  await ctx.step("grant roles (operator CLI)", async () => {
    for (const [u, role] of roles) await grantRole(databaseUrl, u.username, role, ROLE_CLI_TIMEOUT_MS);
  });
  const staff: Staff = await ctx.step("staff: sign in again to pick up the roles", async () => {
    const [a, b, c, d] = await Promise.all(roles.map(([u]) => p.users.signIn(u)));
    return { l1: a as SignedInUser, l2: b as SignedInUser, mod: c as SignedInUser, admin: d as SignedInUser };
  });
  const emails = [l1, l2, mod, admin].map((u) => u.email);
  // The tick as of now is what the worker's own per-minute schedule does: harmless, and it
  // fails early with a clear message when the override (test hooks) is not applied.
  await ctx.step("hooks: the test hooks answer (MODERATION_TEST_HOOKS=true)", () =>
    hooks.nciiTick(new Date().toISOString()),
  );

  const { probe } = via === "web" ? await playerBundles() : { probe: "" };
  const run: Run = {
    ctx,
    via,
    sampleSeconds,
    deadlineMs,
    databaseUrl,
    hooks,
    staff,
    emails,
    needles,
    sessions,
    probe,
    check,
    anon: () => p.api().client,
    webSession: async (label, user) => {
      const session = await WebSession.open({
        fleet: p.fleet,
        engine: "chromium",
        webUrl: ctx.env.HARNESS_WEB_URL,
        probeScript: probe,
        label,
        log: ctx.log,
      });
      sessions.push(session);
      if (user) {
        await ctx.step(`${label}: sign in through the web UI`, async () => {
          const page = await session.goto(ROUTES.signin);
          await signInViaUi(page, user, UI_TIMEOUT_MS, ctx.signal);
          await byTestId(page, T.navUser, { username: user.username }).waitFor({ timeout: UI_TIMEOUT_MS });
        });
      }
      return session;
    },
  };

  let step1: Step1Result | null = null;
  for (const n of steps) {
    const since = new Date(Date.now() - 2_000);
    switch (n) {
      case 1:
        step1 = await stepT0Live(run);
        break;
      case 2:
        if (step1) await stepEvidenceSurvives(run, step1);
        break;
      case 3:
        await stepTwoReviewers(run);
        break;
      case 4:
        await stepT2Label(run);
        break;
      case 5:
        await stepT1Restrict(run);
        break;
      case 6:
        await stepUploadRejected(run);
        break;
      case 7:
        await stepNcii(run);
        break;
    }
    await logHygiene(run, n, since);
  }
}

// ---------------------------------------------------------------- shared

function title(n: SafetyStep, what: string): string {
  return `${n}. ${SAFETY_STEPS[n]}: ${what}`;
}

async function logHygiene(run: Run, n: SafetyStep, since: Date): Promise<void> {
  const { ctx } = run;
  const hits = await ctx.step(title(n, "log hygiene (podman logs since the step began)"), async () => {
    const needles = [...run.needles, ...emailNeedles(run.emails)];
    const containers = await serviceContainers(ctx.env.HARNESS_CONTAINER_PREFIX);
    ctx.assert(
      `${n}: service containers found for log scanning (prefix ${ctx.env.HARNESS_CONTAINER_PREFIX})`,
      containers.length > 0,
    );
    const all = [];
    for (const c of containers) all.push(...scanLog(c.service, await containerLogs(c.name, since), needles));
    ctx.data(`logs.step${n}`, { containers: containers.map((c) => c.service), hits: summarizeHits(all) });
    return all;
  });
  // The hit summary names the source and the kind of data, never the matching text.
  ctx.assert(
    `${n}: service logs carry no frame data, URLs, requester text or emails`,
    hits.length === 0,
    summarizeHits(hits),
  );
}

async function newStreamer(run: Run, prefix: string): Promise<Streamer> {
  const user = await run.ctx.platform.signUp({ prefix });
  run.emails.push(user.email);
  const channel = user.me.channelSlug ?? user.username;
  const c = await user.api.client.channels.get({ channel });
  return { user, channel, channelId: c.id };
}

/** A publisher on the streamer's freshly rotated key, stopped when the scenario ends. */
async function publisher(
  run: Run,
  s: Streamer,
  source: { image: string } | { lavfi: string },
): Promise<{ pub: FixturePublisher; url: string }> {
  const { key } = await s.user.api.client.stream.rotateKey({ channel: s.channel });
  const url = rtmpPublishUrl(run.ctx.env.HARNESS_RTMP_URL, key);
  const pub = new FixturePublisher(`publisher-${s.channel}`, { url, ...source }, run.ctx.log);
  run.ctx.defer(() => pub.stop(1_000));
  return { pub, url };
}

function benign(run: Run, salt: number): { lavfi: string } {
  return { lavfi: benignPatternSource((runSeed(run.ctx.runId) + salt) & 0x7fffffff) };
}

async function waitLive(run: Run, channel: string): Promise<number> {
  await waitFor(`${channel} live`, async () => (await run.anon().channels.get({ channel })).live !== null, {
    timeoutMs: API_SETTLE_MS,
    intervalMs: 250,
    signal: run.ctx.signal,
  });
  return Date.now();
}

