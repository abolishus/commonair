/** Every evidence object opens with the test private key and matches its plaintext sha256. */
async function expectEvidenceOpens(t0: ModerationT0Job): Promise<void> {
  expect(t0.evidence.length).toBeGreaterThanOrEqual(2);
  for (const e of t0.evidence) {
    const plain = await opener.open(Buffer.from(e.sealedBase64, "base64"));
    expect(await plaintextSha256(plain)).toBe(e.sha256);
    expect(plain.byteLength).toBe(e.sizeBytes);
  }
  const luma = t0.evidence.find((e) => e.pdq !== null);
  expect(luma).toMatchObject({ kind: "frame", contentType: "image/png" });
  expect(luma?.pdqQuality).toBeGreaterThanOrEqual(50);
}

