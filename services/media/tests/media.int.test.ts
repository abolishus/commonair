type MediaStorage = MediaService["ctx"]["storage"];

/** The service's storage with some operations wrapped (the wrapper gets the real storage first). */
function hooked(overrides: {
  copy?: (target: MediaStorage, bucket: string, from: string, to: string) => Promise<void>;
}): MediaStorage {
  return new Proxy(media.ctx.storage, {
    get(target, property) {
      if (property === "copy" && overrides.copy) {
        const copy = overrides.copy;
        return (bucket: string, from: string, to: string) => copy(target, bucket, from, to);
      }
      const value = Reflect.get(target, property);
      return typeof value === "function" ? value.bind(target) : value;
    },
  });
}

async function keysUnder(prefix: string): Promise<string[]> {
  const keys: string[] = [];
  for await (const o of media.ctx.storage.list(BUCKET, prefix)) keys.push(o.key);
  return keys;
}

/**
 * A public pattern VOD whose finalize job is parked (delayed an hour under its job id), so the
 * service's stale-VOD reconcile leaves it to the test's own `finalizeVod` call.
 */
async function parkedPatternVod(): Promise<{ vodId: string; broadcastId: string }> {
  const id = uuidv7();
  await finalizeQueue.add("finalize", { vodId: id }, { jobId: id, delay: 3_600_000 });
  return uploadPatternVod(id);
}

/** A VOD of the synthetic T0 pattern, recorded as fMP4 HLS and uploaded like the recorder does. */
/** The barrier, or a clear failure if finalizeVod finished without reaching it (no 60 s hang). */
async function barrierOrResult(barrier: Promise<void>, finalizing: Promise<string>): Promise<void> {
  let reached = false;
  await Promise.race([
    barrier.then(() => {
      reached = true;
    }),
    // Settles after the barrier in the normal case; only an early finish is an error.
    finalizing.then(
      (r) => {
        if (!reached) throw new Error(`finalizeVod returned "${r}" before reaching the barrier`);
      },
      (err: unknown) => {
        if (!reached) throw err;
      },
    ),
  ]);
}

async function uploadPatternVod(id = uuidv7()): Promise<{ vodId: string; broadcastId: string }> {
  const bid = uuidv7();
  const at = new Date(Date.now() - 60_000);
  const dir = mkdtempSync(join(tmpdir(), "media-int-vod-"));
  try {
    // Two seconds of a benign test pattern, then the synthetic T0 pattern: the match must be found
    // past the first sample.
    await runCommand(
      "ffmpeg",
      [
        "-hide_banner",
        "-loglevel",
        "error",
        "-f",
        "lavfi",
        "-i",
        "testsrc2=size=1280x720:rate=30:duration=4",
        "-loop",
        "1",
        "-framerate",
        "30",
        "-t",
        "6",
        "-i",
        T0_PATTERN,
        "-filter_complex",
        "[1:v]scale=1280:720,format=yuv420p,setsar=1[p];[0:v]format=yuv420p,setsar=1[t];[t][p]concat=n=2:v=1:a=0[v]",
        "-map",
        "[v]",
        "-c:v",
        "libx264",
        "-preset",
        "veryfast",
        "-g",
        "60",
        "-f",
        "hls",
        "-hls_time",
        "2",
        "-hls_list_size",
        "0",
        "-hls_segment_type",
        "fmp4",
        "-hls_fmp4_init_filename",
        "init.mp4",
        "-hls_segment_filename",
        `${dir}/seg_%03d.m4s`,
        `${dir}/${VOD_PLAYLIST}`,
      ],
      { timeoutMs: 60_000 },
    );
    const text = await Bun.file(`${dir}/${VOD_PLAYLIST}`).text();
    // A recording in progress has no ENDLIST; finalize closes it only when it publishes.
    await media.ctx.storage.put(BUCKET, vodPrefix(id, "private") + VOD_PLAYLIST, text.replace("#EXT-X-ENDLIST", ""), {
      contentType: "application/vnd.apple.mpegurl",
    });
    for (const name of ["init.mp4", ...text.split("\n").filter((l) => l.endsWith(".m4s"))])
      await media.ctx.storage.put(
        BUCKET,
        vodPrefix(id, "private") + name,
        await Bun.file(`${dir}/${name.trim()}`).bytes(),
        {
          contentType: "video/mp4",
        },
      );
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
  // Rows last: the service's stale-VOD reconcile queues a `recording` VOD of an ended broadcast at
  // once, and its own finalize job must not win the race against the test's barrier.
  await tdb.db.insert(schema.broadcasts).values({
    id: bid,
    channelId,
    ingestProtocol: "rtmp",
    path: `live/${SLUG}`,
    title: "pattern vod",
    startedAt: at,
    endedAt: new Date(at.getTime() + 8_000),
  });
  await tdb.db.insert(schema.vods).values({
    id,
    broadcastId: bid,
    channelId,
    title: "pattern vod",
    status: "recording",
    storagePrefix: vodPrefix(id, "private"),
  });
  return { vodId: id, broadcastId: bid };
}

/** Publish and announce a broadcast without waiting for a session (a tainted path gets none). */
async function goLiveNoWait(image: string): Promise<string> {
  publisher = publishTestPattern(`rtmp://127.0.0.1:${mtx.port("1935/tcp")}/live/${SLUG}?key=streamkey`, { image });
  await waitFor("source ready in MediaMTX", async () => (await mtxApi.getPath(`live/${SLUG}`))?.ready);
  const id = uuidv7();
  const at = new Date();
  await tdb.db.insert(schema.broadcasts).values({
    id,
    channelId,
    ingestProtocol: "rtmp",
    path: `live/${SLUG}`,
    title: "reconnect",
    startedAt: at,
  });
  await publish({
    type: "online",
    channelId,
    broadcastId: id,
    slug: SLUG,
    path: `live/${SLUG}`,
    protocol: "rtmp",
    at: at.toISOString(),
  });
  return id;
}

async function createClip(startOffset: number, durationSeconds: number): Promise<string> {
  const id = uuidv7();
  await tdb.db.insert(schema.clips).values({
    id,
    channelId,
    broadcastId,
    title: "clip",
    startOffset,
    durationSeconds,
  });
  await media.jobs.enqueueClip(id);
  return id;
}

async function waitForClip(id: string) {
  return waitFor("clip finished", async () => {
    const [c] = await tdb.db.select().from(schema.clips).where(eq(schema.clips.id, id));
    return c && c.status !== "processing" ? c : null;
  });
}

async function mp4Duration(key: string): Promise<number> {
  const res = await media.ctx.storage.get(BUCKET, key);
  if (!res) throw new Error(`missing ${key}`);
  const file = join(workDir, `check-${crypto.randomUUID()}.mp4`);
  await Bun.write(file, res);
  const { stdout } = await runCommand(
    "ffprobe",
    ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file],
    { timeoutMs: 15_000 },
  );
  return Number.parseFloat(new TextDecoder().decode(stdout));
}
