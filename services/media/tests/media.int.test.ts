async function goLive(image?: string): Promise<{ id: string; startedAt: Date }> {
  publisher = publishTestPattern(`rtmp://127.0.0.1:${mtx.port("1935/tcp")}/live/${SLUG}?key=streamkey`, { image });
  await waitFor("source ready in MediaMTX", async () => (await mtxApi.getPath(`live/${SLUG}`))?.ready);
  const id = uuidv7();
  const at = new Date();
  await tdb.db.insert(schema.broadcasts).values({
    id,
    channelId,
    ingestProtocol: "rtmp",
    path: `live/${SLUG}`,
    title: "Integration test",
    startedAt: at,
  });
  await publish({
    type: "online",
    channelId,
    broadcastId: id,
    slug: SLUG,
    path: `live/${SLUG}`,
    protocol: "rtmp",
    at: at.toISOString(),
  });
  await waitFor("session started", async () => media.coordinator.session(id));
  return { id, startedAt: at };
}

